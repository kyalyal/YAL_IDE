    '# 모델: 기본은 gpt-6.1-sol 로 고정한다. 바꾸려면 GPT_MODEL 환경변수를 지정한다.',
    '# --approve-for-me: Windows에서 workspace-write 샌드박스가 읽기전용으로 떨어지는 문제를 피하기 위해 사용',
    'set -euo pipefail',
